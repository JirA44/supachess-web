export const PIECE_VALUES = {
  p: 100,
  n: 320,
  b: 330,
  r: 500,
  q: 900,
  k: 20000
} as const;

export type PieceType = keyof typeof PIECE_VALUES;

export function flipSquare(sq: number): number {
  return (7 - Math.floor(sq / 8)) * 8 + (sq % 8);
}

export function getPSTValue(pieceType: PieceType, sq: number, isWhite: boolean, isEndgame: boolean): number {
  const flipped = isWhite ? sq : flipSquare(sq);
  switch (pieceType) {
    case 'p': return PST.p[flipped];
    case 'n': return PST.n[flipped];
    case 'b': return PST.b[flipped];
    case 'r': return PST.r[flipped];
    case 'q': return PST.q[flipped];
    case 'k': return isEndgame ? PST.k_eg[flipped] : PST.k_mg[flipped];
    default: return 0;
  }
}